def normalize(name: str) -> str:
    return re.sub(r"[^0-9a-z]", "", name.casefold())


def collect(registry: str) -> dict[str, str]:
    """prefix (6, 7 or 9 hex digits) -> brand."""
    wanted = {normalize(org): brand for brand, orgs in BRANDS.items() for org in orgs}
    prefixes: dict[str, str] = {}
    for name in FILES:
        with open(os.path.join(registry, name), newline="", encoding="utf-8") as source:
            rows = csv.reader(source)
            header = next(rows)
            if header[:3] != ["Registry", "Assignment", "Organization Name"]:
                raise SystemExit(f"{name}: unexpected header {header[:3]}")
            for row in rows:
                if len(row) < 3:
                    continue
                brand = wanted.get(normalize(row[2]))
                assignment = row[1].strip().upper()
                if brand and re.fullmatch(r"[0-9A-F]{6}|[0-9A-F]{7}|[0-9A-F]{9}", assignment):
                    prefixes[assignment] = brand
    missing = sorted(set(BRANDS) - set(prefixes.values()))
    if missing:
        raise SystemExit(f"no registry entries found for: {', '.join(missing)}")
    return prefixes


def render(prefixes: dict[str, str], date: str) -> str:
    lines = [
        '"""Camera vendor MAC prefixes. Generated by tools/gen_oui.py; do not edit.',
        "",
        f"Source: IEEE Registration Authority MA-L/MA-M/MA-S public listings, retrieved {date}.",
        "Exact organization names only; OEM rebrands report the real manufacturer, and",
        "Wi-Fi cameras may carry their radio module's prefix or a random MAC.",
        '"""',
        "",
        f'REGISTRY_DATE = "{date}"',
        "PREFIXES = {",
    ]
    lines += [f'    "{prefix}": "{brand}",' for prefix, brand in sorted(prefixes.items())]
    lines += [
        "}",
        "",
        "",
        "def vendor(mac: str | None) -> str | None:",
        '    """Brand for a MAC address by longest registered prefix (36, 28, then 24 bits)."""',
        '    compact = "".join(ch for ch in (mac or "").upper() if ch in "0123456789ABCDEF")',
        "    if len(compact) != 12:",
        "        return None",
        "    for length in (9, 7, 6):",
        "        brand = PREFIXES.get(compact[:length])",
        "        if brand:",
        "            return brand",
        "    return None",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--registry", required=True, help="directory with the three CSV files")
    parser.add_argument("--date", required=True, help="retrieval date, YYYY-MM-DD")
    parser.add_argument("--out", default="shimlib/oui.py")
    args = parser.parse_args(argv)
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", args.date):
        parser.error("--date must be YYYY-MM-DD")
    prefixes = collect(args.registry)
    with open(args.out, "w") as out:
        out.write(render(prefixes, args.date))
    counts: dict[str, int] = {}
    for brand in prefixes.values():
        counts[brand] = counts.get(brand, 0) + 1
    print(f"{args.out}: {len(prefixes)} prefixes, {len(counts)} brands")
    for brand in sorted(counts):
        print(f"  {brand:<12} {counts[brand]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
