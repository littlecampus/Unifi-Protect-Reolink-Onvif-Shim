#!/usr/bin/env python3
"""Generate shimlib/oui.py (camera vendor MAC prefixes) from the IEEE registry.

Development tool; not shipped to the console. Download the public listings into
an empty directory, then regenerate and review the diff:

    mkdir -p /tmp/ieee-oui && cd /tmp/ieee-oui
    curl -fsSLo oui.csv   https://standards-oui.ieee.org/oui/oui.csv
    curl -fsSLo mam.csv   https://standards-oui.ieee.org/oui28/mam.csv
    curl -fsSLo oui36.csv https://standards-oui.ieee.org/oui36/oui36.csv
    cd - && python3 tools/gen_oui.py --registry /tmp/ieee-oui --date YYYY-MM-DD

Organizations are matched by their exact registered name (normalized for case and
punctuation), never by substring: "Dahua" would also match a weighing-scale maker,
and generic words like "techwin" match unrelated companies. TP-Link is excluded on
purpose (hundreds of prefixes, mostly routers).
"""

