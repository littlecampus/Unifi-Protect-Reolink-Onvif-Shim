"""Paths and systemd unit text for the NVR-local shim.

Units carry no credentials or camera addresses: the per-camera template takes
only the camera id (%i); everything else is read from the inventory file.
"""

from __future__ import annotations

from dataclasses import dataclass

TEMPLATE = "onvif-shim@.service"
RECONCILE_SERVICE = "onvif-shim-reconcile.service"
RECONCILE_TIMER = "onvif-shim-reconcile.timer"
UNIT_FILES = (TEMPLATE, RECONCILE_SERVICE, RECONCILE_TIMER)
RUNTIME_NAME = "onvif-shim"


def instance(camera_id: str) -> str:
    return f"onvif-shim@{camera_id}.service"


@dataclass(frozen=True)
class Paths:
    base: str = "/data/onvif-shim"
    unit_dir: str = "/etc/systemd/system"
    run_dir: str = "/run/onvif-shim"
    lock_file: str = "/run/onvif-shim-ctl.lock"
    python: str = "/usr/bin/python3"

    @property
    def config(self) -> str:
        return f"{self.base}/cameras.json"

    @property
    def releases(self) -> str:
        return f"{self.base}/releases"

    @property
    def current(self) -> str:
        return f"{self.base}/current"

    @property
    def state(self) -> str:
        return f"{self.base}/state"

    @property
    def backups(self) -> str:
        return f"{self.base}/backups"

    @property
    def bypass_flag(self) -> str:
        return f"{self.state}/bypass-all"

    def status_file(self, camera_id: str) -> str:
        return f"{self.run_dir}/{camera_id}/status.json"


def render(paths: Paths) -> dict[str, str]:
    ctl = f"{paths.python} -I {paths.current}/shimctl.py"
    defaults = Paths()
    opts = f"--base {paths.base}"
    for flag, value, default in (
        ("--unit-dir", paths.unit_dir, defaults.unit_dir),
        ("--run-dir", paths.run_dir, defaults.run_dir),
        ("--lock-file", paths.lock_file, defaults.lock_file),
    ):
        if value != default:
            opts += f" {flag} {value}"
    template = f"""\
# Generated by shimctl.py; edits are overwritten by install/reconcile.
[Unit]
Description=ONVIF NVR shim for camera %i
Documentation=file://{paths.current}/README.md
After=network-online.target
Wants=network-online.target
# Bounded recovery: after 5 failed starts in 10 minutes the unit stays failed
# (redirect removed, alert raised) until an operator runs `shimctl.py reset`.
StartLimitIntervalSec=600
StartLimitBurst=5

[Service]
Type=notify
NotifyAccess=main
ExecStart={paths.python} -I {paths.current}/onvif_shim.py --config {paths.config} \\
    --camera %i --status-dir %t/{RUNTIME_NAME}/%i
# '+' = privileged helper (firewall); '-' = never fail the unit because of it.
# ExecStop runs before SIGTERM: Protect's new connections go direct while the
# shim drains in-flight requests. ExecStopPost repeats it (covers crashes).
ExecStartPost=-+{ctl} activate %i {opts}
ExecStop=-+{ctl} deactivate %i {opts}
ExecStopPost=-+{ctl} deactivate %i {opts}
Restart=on-failure
RestartSec=5
RestartPreventExitStatus=78
TimeoutStartSec=30
TimeoutStopSec=40
WatchdogSec=30
SyslogIdentifier=onvif-shim
Environment=PYTHONDONTWRITEBYTECODE=1
DynamicUser=yes
RuntimeDirectory={RUNTIME_NAME}/%i
RuntimeDirectoryMode=0755
UMask=0022
NoNewPrivileges=yes
CapabilityBoundingSet=
AmbientCapabilities=
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
PrivateDevices=yes
ProtectKernelTunables=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectControlGroups=yes
ProtectClock=yes
ProtectHostname=yes
ProtectProc=invisible
RestrictAddressFamilies=AF_INET AF_UNIX
RestrictNamespaces=yes
RestrictRealtime=yes
RestrictSUIDSGID=yes
LockPersonality=yes
MemoryDenyWriteExecute=yes
SystemCallArchitectures=native
SystemCallFilter=@system-service
SystemCallErrorNumber=EPERM
MemoryMax=96M
TasksMax=16
LimitNOFILE=512
CPUWeight=50
OOMScoreAdjust=500
LogRateLimitIntervalSec=60
LogRateLimitBurst=120

[Install]
WantedBy=multi-user.target
"""
    service = f"""\
# Generated by shimctl.py; edits are overwritten by install/reconcile.
[Unit]
Description=Reconcile ONVIF NVR shim instances and redirects
Documentation=file://{paths.current}/README.md

[Service]
Type=oneshot
ExecStart={ctl} reconcile --quiet {opts}
TimeoutStartSec=90
SyslogIdentifier=onvif-shim-ctl
"""
    timer = """\
# Generated by shimctl.py. This timer lives on the NVR: a UniFi OS update that
# removes it also removes its protection; see the post-update checklist.
[Unit]
Description=Periodic ONVIF NVR shim reconcile (fail-open health gate)

[Timer]
OnBootSec=45
OnUnitActiveSec=30
AccuracySec=5

[Install]
WantedBy=timers.target
"""
    return {TEMPLATE: template, RECONCILE_SERVICE: service, RECONCILE_TIMER: timer}
